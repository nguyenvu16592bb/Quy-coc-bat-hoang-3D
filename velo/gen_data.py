# Generates data.v from the JSON files in assets/data/ (monsters, boss, team,
# skills, particles, effects, levels). Run:  python gen_data.py
import json
import io
import os

BASE = r'C:\New folder\Hangrong\merge-game\assets\data'
OUT = r'C:\New folder\Hangrong\merge-game\data.v'

def load(name):
    with io.open(os.path.join(BASE, name), encoding='utf-8') as f:
        return json.load(f)

m = load('monsters.json')
b = load('boss.json')
t = load('team.json')
sk = load('skills.json')
pt = load('particles.json')
ef = load('effects.json')
lv = load('levels.json')

els, ens = m['elements'], m['enemies']
skills = sk['skills']
effects = ef['effects']
particles = pt['particles']
bosses = b['list']
team = t['default']

# array sizes (the "max arrays" — extend here + in the JSONs)
TEAM_N, ENEMY_N, SKILL_N, EFFECT_N, PARTICLE_N, BOSS_N = 8, 20, 24, 13, 16, 10

def q(s):
    return "'" + s.replace("'", "\\'") + "'"

lines = []
lines.append('''module main

// ===========================================================================
// Game data — GENERATED by gen_data.py from the JSON files in assets/data/.
// Do not edit by hand: change the JSON (monsters.json, boss.json, team.json,
// skills.json, particles.json, effects.json, levels.json), then run
// `python gen_data.py`. The JSON files are the source of truth; this V file
// is compiled into the game (the web runtime cannot parse JSON dynamically).
// ===========================================================================

struct ElementData {
\thp     f32
\tdmg    f32
\tspd    f32
\tranged bool
\trange  f32
\ttex    string
\tproj   string
\tskill  string
}

struct EnemyData {
\thp     f32
\tdmg    f32
\tspd    f32
\tranged bool
\trange  f32
\ttex    string
\tsize   [2]f32
\ttint   [3]f32
}

struct ParticleData {
\tcount    int
\tsize     f32
\tspeed    f32
\tlifetime f32
\ttexture  string
}

struct SkillData {
\tskill_type string
\tdmg_mult   f32
\trange      f32
\tcount      int
\teffect     string
}

struct EffectData {
\teffect_type string
\tvalue       f32
\tdmg_mult    f32
\tduration    f32
}

struct TeamSlot {
\telement string
\tlevel   int
}

struct BossData {
pub mut:
\tevery       int
\thp_mult     f32
\tdmg_mult    f32
\tspd         f32
\tskill       string
\ttex         string
\tsize_scale  f32
\treward_mult f32
\tname        string
\ttint        [3]f32
}

struct LevelTuning {
pub mut:
\tcount       int
\tbase_reward int
\treward_step int
\twaves_min   int
\twaves_max   int
\tcount_base  int
\tcount_step  int
\tmtype_scale int
\tlevel_scale int
}

struct GameData {
pub mut:
\telements   [{EL_N}]ElementData
\tenemies    [{ENEMY_N}]EnemyData
\tparticles  [{PARTICLE_N}]ParticleData
\tskills     [{SKILL_N}]SkillData
\teffects    [{EFFECT_N}]EffectData
\tteam       [{TEAM_N}]TeamSlot
\tboss       BossData
\tbosses     [{BOSS_N}]BossData
\tlevel_mult f32
\tlevels     LevelTuning
\tready      bool
}

__global (
\tg_data GameData
)

fn element_index(e string) int {
\treturn match e {
\t\t'fire'  { 0 }
\t\t'water' { 1 }
\t\t'earth' { 2 }
\t\t'wind'  { 3 }
\t\t'lightning' { 4 }
\t\t'ice'   { 5 }
\t\t'steam' { 6 }
\t\t'lava'  { 7 }
\t\t'ember' { 8 }
\t\t'mud'   { 9 }
\t\t'mist'  { 10 }
\t\t'dust'  { 11 }
\t\telse    { 5 }
\t}
}

fn particle_index(tag string) int {
\treturn match tag {
\t\t'spawn'      { 0 }
\t\t'merge'      { 1 }
\t\t'kill'       { 2 }
\t\t'levelup'    { 3 }
\t\t'win'        { 4 }
\t\t'boss_death' { 5 }
\t\t'crit'       { 6 }
\t\t'heal'       { 7 }
\t\t'freeze'     { 8 }
\t\t'banner'     { 9 }
\t\t'meteor'     { 10 }
\t\t'freeze_break' { 11 }
\t\t'stun_star'  { 12 }
\t\t'combo'      { 13 }
\t\t'heal_big'   { 14 }
\t\telse         { 15 }
\t}
}

fn skill_index(s string) int {
\treturn match s {
\t\t'fire_shot'  { 0 }
\t\t'water_bolt' { 1 }
\t\t'earth_slam' { 2 }
\t\t'wind_gust'  { 3 }
\t\t'boss_rain'  { 4 }
\t\t'boss_slam'  { 5 }
\t\t'boss_ice'   { 6 }
\t\t'heal'       { 7 }
\t\t'boss_meteor' { 8 }
\t\t'boss_freeze' { 9 }
\t\t'boss_stunwave' { 10 }
\t\t'ultimate'   { 11 }
\t\t'lightning_strike' { 12 }
\t\t'ice_freeze' { 13 }
\t\t'ember_aura' { 14 }
\t\t'stone_guard' { 15 }
\t\t'nature_regen' { 16 }
\t\t'shadow_hex' { 17 }
\t\t'steam_cloud' { 18 }
\t\t'lava_burst' { 19 }
\t\t'ember_shot' { 20 }
\t\t'mud_slam' { 21 }
\t\t'mist_bolt' { 22 }
\t\t'dust_gust' { 23 }
\t\telse         { 24 }
\t}
}

fn effect_index(e string) int {
\treturn match e {
\t\t'burn'   { 0 }
\t\t'splash' { 1 }
\t\t'stun'   { 2 }
\t\t'knockback' { 3 }
\t\t'freeze' { 4 }
\t\t'poison' { 5 }
\t\t'meteor' { 6 }
\t\t'weak'   { 7 }
\t\t'slow'   { 8 }
\t\t'explode' { 9 }
\t\t'atk_up' { 10 }
\t\t'shield' { 11 }
\t\t'regen'  { 12 }
\t\telse     { 13 }
\t}
}

fn init_game_data() {
\tif g_data.ready {
\t\treturn
\t}
\tg_data.level_mult = {level_mult}
\tg_data.elements = {elements}
\tg_data.enemies = {enemies}
\tg_data.particles = {particles}
\tg_data.skills = {skills}
\tg_data.effects = {effects}
\tg_data.team = {team}
\tg_data.boss = BossData{
\t\tevery:       {boss_every}
\t\thp_mult:     {boss_hp}
\t\tdmg_mult:    {boss_dmg}
\t\tspd:         {boss_spd}
\t\tskill:       {boss_skill}
\t\ttex:         {boss_tex}
\t\tsize_scale:  {boss_scale}
\t\treward_mult: {boss_reward}
\t\tname:        {boss_name}
\t\ttint:        [{boss_tint}]!
\t}
\tg_data.bosses = {bosses}
\tg_data.levels = LevelTuning{
\t\tcount:       {lv_count}
\t\tbase_reward: {lv_base}
\t\treward_step: {lv_step}
\t\twaves_min:   {lv_wmin}
\t\twaves_max:   {lv_wmax}
\t\tcount_base:  {lv_cbase}
\t\tcount_step:  {lv_cstep}
\t\tmtype_scale: {lv_mscale}
\t\tlevel_scale: {lv_lscale}
\t}
\tg_data.ready = true
}
''')

el_list = []
for key in ['fire', 'water', 'earth', 'wind', 'lightning', 'ice', 'steam', 'lava', 'ember', 'mud', 'mist', 'dust']:
    e = els[key]
    el_list.append('ElementData{%s, %s, %s, %s, %s, %s, %s, %s}' % (
        e['hp'], e['dmg'], e['spd'], str(e['ranged']).lower(), e['range'],
        q(e['tex']), q(e['proj']), q(e['skill'])))
lines.append('fn element_data(el string) ElementData {\n\treturn g_data.elements[element_index(el)]\n}\n')

en_list = []
for i in range(1, ENEMY_N + 1):
    e = ens.get(str(i))
    if e is None:
        en_list.append("EnemyData{42, 7, 1.7, false, 0, 'enemies/monter1.png', [f32(191), 221]!, [f32(255), 255, 255]!}")
        continue
    tnt = e.get('tint', [255, 255, 255])
    en_list.append('EnemyData{%s, %s, %s, %s, %s, %s, [f32(%s), %s]!, [f32(%s), %s, %s]!}' % (
        e['hp'], e['dmg'], e['spd'], str(e['ranged']).lower(), e['range'],
        q(e['tex']), e['size'][0], e['size'][1], tnt[0], tnt[1], tnt[2]))
lines.append('fn enemy_data(mtype int) EnemyData {\n\tidx := if mtype < 1 { 0 } else if mtype > %d { %d } else { mtype - 1 }\n\treturn g_data.enemies[idx]\n}\n' % (ENEMY_N, ENEMY_N - 1))

pt_tags = ['spawn', 'merge', 'kill', 'levelup', 'win', 'boss_death', 'crit', 'heal', 'freeze', 'banner', 'meteor', 'freeze_break', 'stun_star', 'combo', 'heal_big', 'explode']
pt_list = []
for tag in pt_tags:
    p = particles.get(tag)
    if p is None:
        p = {'count': 16, 'size': 16, 'speed': 110, 'lifetime': 0.6, 'texture': 'fx/proj_fire.png'}
    pt_list.append('ParticleData{%s, %s, %s, %s, %s}' % (
        p['count'], p['size'], p['speed'], p['lifetime'], q(p['texture'])))
lines.append('fn particle_data(tag string) ParticleData {\n\treturn g_data.particles[particle_index(tag)]\n}\n')

sk_keys = ['fire_shot', 'water_bolt', 'earth_slam', 'wind_gust', 'boss_rain', 'boss_slam', 'boss_ice', 'heal', 'boss_meteor', 'boss_freeze', 'boss_stunwave', 'ultimate', 'lightning_strike', 'ice_freeze', 'ember_aura', 'stone_guard', 'nature_regen', 'shadow_hex', 'steam_cloud', 'lava_burst', 'ember_shot', 'mud_slam', 'mist_bolt', 'dust_gust']
sk_list = []
for key in sk_keys:
    s = skills.get(key)
    if s is None:
        s = {'type': 'melee', 'dmg_mult': 1.0, 'range': 0, 'count': 1, 'effect': ''}
    sk_list.append('SkillData{%s, %s, %s, %s, %s}' % (
        q(s['type']), s['dmg_mult'], s['range'], s['count'], q(s['effect'])))
lines.append('fn skill_data(s string) SkillData {\n\treturn g_data.skills[skill_index(s)]\n}\n')

ef_keys = ['burn', 'splash', 'stun', 'knockback', 'freeze', 'poison', 'meteor', 'weak', 'slow', 'explode', 'atk_up', 'shield', 'regen']
ef_list = []
for key in ef_keys:
    e = effects.get(key)
    if e is None:
        e = {'type': 'none', 'value': 0, 'duration': 0}
    ef_list.append('EffectData{%s, %s, %s, %s}' % (
        q(e['type']), e['value'], e.get('dmg_mult', 0.0), e.get('duration', 0.0)))
lines.append('fn effect_data(e string) EffectData {\n\treturn g_data.effects[effect_index(e)]\n}\n')

tm_list = []
for slot in team[:TEAM_N]:
    tm_list.append('TeamSlot{%s, %s}' % (q(slot['element']), slot['level']))
while len(tm_list) < TEAM_N:
    tm_list.append("TeamSlot{'', 0}")
lines.append('fn team_slots() []TeamSlot {\n\treturn g_data.team[..]\n}\n')

# boss list
bo_list = []
for i in range(BOSS_N):
    bb = bosses[i] if i < len(bosses) else bosses[0]
    tnt = bb.get('tint', [255, 255, 255])
    bo_list.append('BossData{10, %s, %s, %s, %s, %s, %s, %s, %s, [f32(%s), %s, %s]!}' % (
        bb['hp_mult'], bb['dmg_mult'], bb['spd'], q(bb['skill']), q(bb['tex']),
        bb['size_scale'], bb['reward_mult'], q(bb['name']), tnt[0], tnt[1], tnt[2]))
lines.append('fn boss_count() int {\n\treturn g_data.bosses.len\n}\n')
lines.append('fn boss_index(n int) int {\n\tmut idx := 0\n\tif g_data.boss.every > 0 {\n\t\tidx = (n / g_data.boss.every) - 1\n\t}\n\tif idx < 0 {\n\t\tidx = 0\n\t}\n\treturn idx %% %d\n}\n' % BOSS_N)
lines.append('fn boss_for_level(n int) BossData {\n\treturn g_data.bosses[boss_index(n)]\n}\n')

lines.append('fn level_count() int {\n\treturn g_data.levels.count\n}\n')
lines.append('fn is_boss_level(n int) bool {\n\treturn g_data.boss.every > 0 && n % g_data.boss.every == 0\n}\n')

src = '\n'.join(lines)
repl = {
    '{EL_N}': '12',
    '{TEAM_N}': str(TEAM_N), '{ENEMY_N}': str(ENEMY_N),
    '{SKILL_N}': str(SKILL_N), '{EFFECT_N}': str(EFFECT_N), '{PARTICLE_N}': str(PARTICLE_N),
    '{BOSS_N}': str(BOSS_N),
    '{level_mult}': str(m['level_mult']),
    '{elements}': '[' + ', '.join(el_list) + ']!',
    '{enemies}': '[' + ', '.join(en_list) + ']!',
    '{particles}': '[' + ', '.join(pt_list) + ']!',
    '{skills}': '[' + ', '.join(sk_list) + ']!',
    '{effects}': '[' + ', '.join(ef_list) + ']!',
    '{team}': '[' + ', '.join(tm_list) + ']!',
    '{bosses}': '[' + ', '.join(bo_list) + ']!',
    '{boss_every}': str(b['every']), '{boss_hp}': str(bosses[0]['hp_mult']),
    '{boss_dmg}': str(bosses[0]['dmg_mult']), '{boss_spd}': str(bosses[0]['spd']),
    '{boss_skill}': q(bosses[0]['skill']), '{boss_tex}': q(bosses[0]['tex']),
    '{boss_scale}': str(bosses[0]['size_scale']), '{boss_reward}': str(bosses[0]['reward_mult']),
    '{boss_name}': q(bosses[0]['name']),
    '{boss_tint}': 'f32(%s), %s, %s' % (bosses[0]['tint'][0], bosses[0]['tint'][1], bosses[0]['tint'][2]),
    '{lv_count}': str(lv['levels']['count']), '{lv_base}': str(lv['levels']['base_reward']),
    '{lv_step}': str(lv['levels']['reward_step']), '{lv_wmin}': str(lv['levels']['waves_min']),
    '{lv_wmax}': str(lv['levels']['waves_max']), '{lv_cbase}': str(lv['levels']['count_base']),
    '{lv_cstep}': str(lv['levels']['count_step']), '{lv_mscale}': str(lv['levels']['mtype_scale']),
    '{lv_lscale}': str(lv['levels']['level_scale']),
}
for k, v in repl.items():
    src = src.replace(k, v)

io.open(OUT, 'w', encoding='utf-8', newline='\n').write(src)
print('OK regenerated data.v (enemies=%d skills=%d effects=%d bosses=%d)' % (ENEMY_N, SKILL_N, EFFECT_N, BOSS_N))
